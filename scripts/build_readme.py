#!/usr/bin/env python3
"""Render README.md (from templates/README.md.j2) and docs/RANKING.md from
data/projects.yaml and data/categories.yaml. README.md is generated; never hand-edit it."""

from __future__ import annotations

import sys

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from _common import (DOCS, LIST_REPO, NEAR_MISS_N, ROOT, TEMPLATES, TOP_N, as_date, fmt_stars,
                     load_categories, load_projects, ranking_pool)


def cap(text: str) -> str:
    return text[:1].upper() + text[1:] if text else text


def build_context(projects, categories):
    pool = ranking_pool(projects)
    top = pool[:TOP_N]
    near = pool[TOP_N:TOP_N + NEAR_MISS_N]
    rank = {p["id"]: i + 1 for i, p in enumerate(pool)}
    by_cat = []
    for c in categories:
        ranked = [p for p in top if p["category"] == c["id"]]
        picks = [p for p in projects if p["status"] == "practitioner-pick" and p["category"] == c["id"]]
        picks.sort(key=lambda p: -p["stars"])
        if ranked or picks:
            by_cat.append({"cat": c, "ranked": ranked, "picks": picks})
    dates = [as_date(p.get("stars_checked")) for p in projects if p.get("stars_checked")]
    return {
        "categories": by_cat,
        "top": top,
        "near": near,
        "pool": pool,
        "rank": rank,
        "rising": sorted((p for p in projects if p["status"] == "rising"), key=lambda p: -p["stars"]),
        "learning": sorted((p for p in projects if p["status"] == "learning"), key=lambda p: -p["stars"]),
        "review": [p for p in projects if p["status"] == "review"],
        "excluded": [p for p in projects if p["status"] == "excluded"],
        "last_refreshed": max(dates).isoformat() if dates else "never",
        "top_n": TOP_N,
        "cat_title": {c["id"]: c["title"] for c in categories},
        "list_repo": LIST_REPO,
    }


def render_readme(ctx) -> str:
    env = Environment(loader=FileSystemLoader(str(TEMPLATES)), undefined=StrictUndefined,
                      trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True)
    env.filters["cap"] = cap
    env.filters["stars"] = fmt_stars
    return env.get_template("README.md.j2").render(**ctx)


def render_ranking(ctx) -> str:
    lines = ["# Full ranking", "",
             "Generated by `scripts/build_readme.py` from `data/projects.yaml`. Do not hand-edit.",
             f"Last refreshed: {ctx['last_refreshed']}. Stars measure popularity, not quality or production readiness.", "",
             f"## Ranked (top {ctx['top_n']}) and near misses", "",
             "| Rank | Project | Category | Stars | Forks | License | Last push |",
             "|-----:|---------|----------|------:|------:|---------|-----------|"]
    for p in ctx["pool"]:
        r = ctx["rank"][p["id"]]
        marker = "" if r <= ctx["top_n"] else (" (near miss)" if r <= ctx["top_n"] + NEAR_MISS_N else " (unlisted)")
        lic = (p.get("license") or "n/a") + (f" ({p['license_flag']})" if p.get("license_flag") else "")
        pushed = str(p.get("pushed_at") or "")[:10]
        lines.append(f"| {r}{marker} | [{p['name']}](https://github.com/{p['repo']}) | {ctx['cat_title'][p['category']]} | {p['stars']:,} | {p['forks']:,} | {lic} | {pushed} |")
    lines += ["", "## Under review", "",
              "Entries flagged by the integrity rule. They are never ranked until a human approves the status change in a PR.", ""]
    lines += [f"- [{p['name']}](https://github.com/{p['repo']}) - {p['stars']:,} stars, {p['forks']:,} forks. {p['exclusion_reason']}" for p in ctx["review"]] or ["- none"]
    lines += ["", "## Excluded", ""]
    lines += [f"- [{p['name']}](https://github.com/{p['repo']}) - {p['exclusion_reason']}" for p in ctx["excluded"]] or ["- none"]
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    projects = load_projects()
    categories = load_categories()
    ctx = build_context(projects, categories)
    readme = render_readme(ctx)
    ranking = render_ranking(ctx)
    for text, name in ((readme, "README.md"), (ranking, "docs/RANKING.md")):
        bad = [ch for ch in text if ord(ch) > 127]
        if bad:
            print(f"error: {name} would contain non-ASCII characters: {sorted(set(bad))}", file=sys.stderr)
            return 1
    (ROOT / "README.md").write_text(readme)
    DOCS.mkdir(exist_ok=True)
    (DOCS / "RANKING.md").write_text(ranking)
    print(f"README.md: {len(ctx['top'])} ranked, {len(ctx['near'])} near misses, {len(ctx['rising'])} rising, {len(ctx['learning'])} learning")
    print(f"docs/RANKING.md: {len(ctx['pool'])} ranked entries, {len(ctx['review'])} under review, {len(ctx['excluded'])} excluded")
    return 0


if __name__ == "__main__":
    sys.exit(main())
